function [cx]=gfit0(x,y) 
% GFIT0 计算两个向量或矩阵对应列之间的归一化内积。
%
% 输入
%   x, y: 尺寸相同的向量或矩阵。矩阵输入时，sum 默认沿第一维工作。
%
% 输出
%   cx  : 向量输入得到一个标量；m*n 矩阵输入得到 1*n 行向量，
%         cx(j) 是 x(:,j) 与 y(:,j) 的归一化内积，范围通常为 [-1,1]。
%         多列中若只有部分列能量为 0，本函数的整体 if 不能逐列保护；这类输入应使用 gfit1。
%
% 为什么这样算
%   分子 x'*y 衡量同向程度，分母 sqrt((x'*x)(y'*y)) 消除振幅尺度影响。
%   这里没有减去均值，因此它是余弦相似度形式，并非 MATLAB corrcoef 的去均值相关系数。
%
% 例：x=[1,2,3], y=[4,5,6]，nn=32，mm1=14，mm2=77，
%     cx=32/sqrt(14*77)=0.9746。

% 分别得到对应列的点积以及两组数据各自的平方和。
nn=sum(x.*y);
mm1=sum(x.*x);
mm2=sum(y.*y); 
% 任一列全零时分母为 0；两列正交时 nn=0。两种情况都直接输出 0。
if sqrt(mm1.*mm2)==0|nn==0
    cx=0;
    return;
else
    % 用逐元素除法同时处理多列输入。
    cx=nn./sqrt(mm1.*mm2);
end
