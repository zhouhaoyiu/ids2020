function m_out=m2m(m_in)
% M2M 在矩震级 Mw 与标量地震矩 M0 之间换算。
%
% 输入
%   m_in : 一个标量。程序用数值是否小于 20 判断它代表 Mw 还是 M0。
%          m_in < 20  时按矩震级 Mw 处理；m_in >= 20 时按地震矩 M0(N*m)处理。
%
% 输出
%   m_out: 与输入相反的量。输入 Mw 时输出 M0；输入 M0 时输出 Mw。
%
% 计算过程
%   1. 先用 20 作为量级分界，因为通常 Mw 远小于 20，而以 N*m 表示的 M0 远大于 20。
%   2. Mw -> M0 分支直接计算 10 的幂；M0 -> Mw 分支先取 log10，再作线性换算。
%
% 注意
%   当前 Mw -> M0 公式指数前带负号。例如 m2m(7) 得到约 2.51e-20，
%   与常用关系 log10(M0)=1.5*Mw+9.1 不一致。这是原程序的实际行为，
%   这里不改计算语句；调用该分支前应先向作者确认负号是否为笔误。
if m_in<20
    % 当前代码把输入代入负指数，输出一个很小的正数。
    m_out=10.^(-((m_in+6.06666666667)*3/2));
else
    % 例：m_in=10^19.5 N*m 时，m_out=19.5*2/3-6.0667，约为 Mw 6.93。
    m_out=log10(m_in)*2/3-6.06666666667;
end
