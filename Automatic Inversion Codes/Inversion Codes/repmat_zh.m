function m=repmat_zh(n,num)
%==========================================================================
%  m=repmat_zh(n,num)
%  to make m=[n(1,:);n(1,:)...num...;n(1,:);n(2,:)...]
%--------------------------------------------------------------------------
%  Input
%       n: a column vector or a matrix
%     num: decide how many times each row of 'n' be copied
% Output
%      m: has the size of [size(n,1)*num,size(n,2)]
%
% 中文说明
%   输入 n 可以是列向量或矩阵，num 是每一行连续出现的次数。
%   输出 m 的列数不变，行数变为 size(n,1)*num。
%   这样排列是为了给每个上级对象连续配出 num 行数据，例如给每个子断层
%   连续配上全部台站，而不是把整个矩阵整体重复 num 次。
%
% 例 1：n=[1;2;3], num=2，输出 m=[1;1;2;2;3;3]。
%   n'                         -> [1 2 3]
%   repmat(n',[2,1])           -> [1 2 3; 1 2 3]
%   MATLAB 按列读取这个矩阵   -> 1,1,2,2,3,3
%   reshape 后再转置          -> [1;1;2;2;3;3]
%
% 例 2：n=[1 4;2 5;3 6], num=2，输出为
%   [1 4;1 4;2 5;2 5;3 6;3 6]。
%--------------------------------------------------------------------------
%       Zhang Yong, 2012-02-09 12:44, GFZ, Potsdam
%==========================================================================
[~,r]=size(n);
% 先转置再整体重复。此处的中间矩阵还不是最终行顺序。
n=repmat(n',[num,1]);
% 利用 MATLAB 按列存储的顺序重排，再转置，使原 n 的每一行连续复制 num 次。
m=reshape(n,r,[])';
return
%==========================================================================
