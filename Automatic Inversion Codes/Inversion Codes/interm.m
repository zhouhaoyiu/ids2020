function b=interm(a,x)
% INTERM 对二维数组作线性插值，使行、列方向的采样点变密。
%
% 输入
%   a : m*n 数组。每一行和每一列都被看作等间隔采样点。
%   x : 标量或二元素向量。
%       标量 x 同时作为行、列加密倍数；x=[xr,xc] 分别控制行、列方向。
%
% 输出
%   b : 插值后的数组。若两个方向都参与插值，尺寸为
%       ((m-1)*xr+1) * ((n-1)*xc+1)。端点保留，中间值由 interp1 线性插值得到。
%
% 例子
%   a=[0 10;20 30], x=[2 3]
%   第一步沿行方向得到 3*2 的 b0：[0 10;10 20;20 30]；
%   第二步沿列方向把每一行从 2 点加密为 4 点，最终 b 为 3*4：
%   [0 3.3333 6.6667 10; 10 13.3333 16.6667 20; 20 23.3333 26.6667 30]。
sa=size(a);
if isscalar(x)
    % 行坐标由 0:m-1 变成步长 1/x 的新坐标，因此行数增加但数值范围不变。
    b0=interp1(0:sa(1)-1,a,0:1/x:sa(1)-1);
    % 转置后再调用 interp1，相当于用同样倍数沿原数组的列方向插值。
    b00=interp1(0:sa(2)-1,b0',0:1/x:sa(2)-1);
    % 转回“时间/行在第一维”的方向，得到最终二维结果。
    b=b00';
else
    % x(1) 只控制第一维；例如 x(1)=2 会在相邻两行之间插入一个点。
    b0=interp1(0:sa(1)-1,a,0:1/x(1):sa(1)-1);
    if sa(2)~=1
    % 只有多列输入才需要第二维插值；转置是为了让 interp1 沿第一维工作。
    b00=interp1(0:sa(2)-1,b0',0:1/x(2):sa(2)-1);
    b0=b00;
    end
    % 对多列输入，这一步恢复原方向；对单列输入，它把行向量结果转成列向量。
    b=b0';
end
