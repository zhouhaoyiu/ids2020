function e=encuv(a,len)
% ENCUV 计算波形在滑动时间窗内的平方和，即局部能量。
%
% 输入
%   a   : 二维或三维数组。第一维必须是时间采样点；其余维可表示台站、分量等。
%   len : 用来确定窗口半宽的数值。程序实际使用 round(len/2) 作为半窗长。
%
% 输出
%   e   : 与 a 尺寸相同。e(i,...) 是 a 在第 i 点前后一个窗口内的平方和。
%         首尾超出原波形的部分按 0 处理，因此不会缩短输出。
%
% 为什么计算平方和
%   波形有正有负，直接相加可能互相抵消；平方后均为非负数，可表示该时间窗内的能量强弱。
%
% 例：a=[1;2;3], len=1。round(1/2)=1，所以每点使用前、中、后共 3 点：
%   补零后的 al=[0;1;2;3;0]，输出 e=[0^2+1^2+2^2; 1^2+2^2+3^2; 2^2+3^2+0^2]
%   即 e=[5;14;13]。len 不是幂次；代码始终使用 .^2。
sa=size(a);dim=length(sa);
% sa 给出各维长度；二维输入的 sa=[时间点数,列数]，三维输入再多一个第三维长度。
len=round(len/2);
% 把输入的窗口参数换成左右半窗长。实际窗口总点数为 2*len+1。
if dim==2
% 在第一维首尾各补 len 行 0，使边界点也能使用相同长度的窗口。
al=[zeros(len,sa(2));a;zeros(len,sa(2))]; 
elseif dim==3
    % 三维输入只沿时间轴补零，第二、三维尺寸保持不变。
    al=[zeros(len,sa(2),sa(3));a;zeros(len,sa(2),sa(3))];
end

% 先建立与输入同尺寸的输出，循环中逐个时间点写入局部能量。
e=zeros(sa);
for i=1:sa(1)
    if dim==2
    % 对窗口内每个元素平方，再沿第一维求和；输出是一行，对应所有列。
    e(i,:)=sum(al(i:i+len*2,:).^2,1); 
    elseif dim==3
        % 三维情况同样沿第一维求和，保留台站和第三维索引。
        e(i,:,:)=sum(al(i:i+len*2,:,:).^2,1);
    end
end
